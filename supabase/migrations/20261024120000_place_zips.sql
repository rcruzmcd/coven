-- Place question, phase 2 (#1700, part of #1698): the ZIP shortcut, aliases
-- shown as matched, and "township" finding "Twp"
-- ---------------------------------------------------------------------------
--
-- THE ZIP SHORTCUT. Typing five digits into a place question suggests the
-- places that ZIP covers. A ZIP is a mail route, not a place: it crosses
-- municipal lines, and an NYC ZIP spans several neighborhoods, so it maps to
-- every place it meaningfully overlaps and the registrant picks one. A ZIP is
-- never an answer and is never stored with one; the answer is the place.
--
-- place_zips is the mapping, from the Census 2020 ZCTA relationship files
-- (and, for NYC neighborhoods, NYC Planning's tract-to-NTA equivalency),
-- loaded by the next migration (generated by `bun run places:overlays`).
-- Like places it is platform-wide, readable by anyone and written only by
-- migrations, so no third-party API is called at runtime.
--
-- ALIASES SHOWN. places.aliases has always been searched; now search_places
-- also says which alias matched when the place's own label does not, so the
-- picker can show "Ironbound (Newark, Essex Co., NJ)" and the registrant sees
-- why Newark came up. The answer still keeps the place's own label.

create table public.place_zips (
  zip text not null check (zip ~ '^[0-9]{5}$'),
  place_id uuid not null references public.places (id) on delete cascade,
  -- The share of the ZIP's land the place covers, 0-1: ranking only.
  share real not null check (share >= 0 and share <= 1),
  primary key (zip, place_id)
);

comment on table public.place_zips is
  'Platform-wide ZIP (Census ZCTA) to place mapping for the place question''s ZIP shortcut (#1700): every place a ZIP meaningfully overlaps, with its share of the ZIP''s land. Readable by anyone; written only by migrations. Sources and vintages: docs/spec/events.md.';

alter table public.place_zips enable row level security;

revoke all on public.place_zips from public, anon, authenticated;
grant select on public.place_zips to anon, authenticated;

create policy "place_zips select" on public.place_zips
  for select to anon, authenticated
  using (true);

