-- The return type gains `matched`, so the function is replaced, not altered.
drop function public.search_places(text, text, uuid[]);

-- The autocomplete. As in #1699, at most 10 places of the kinds the
-- granularity allows (locality, neighborhood or area), places inside p_area
-- first. Two ways in:
--
--   five digits   the places that ZIP covers: NYC neighborhoods ahead of
--                 the borough at neighborhood granularity, then by the share
--                 of the ZIP each covers. A ZIP finds no state or county, so
--                 `area` returns nothing for one.
--   words         every word typed starts a word of the name, label or an
--                 alias. "township" and "twp", and "borough" and "boro", are
--                 the same word, since labels abbreviate them. Ranked as
--                 before: exact name or alias, then a name or alias that starts
--                 with what was typed, then population, then municipalities
--                 ahead of CDPs, then the shorter label.
--
-- `matched` is the alias that matched when the label alone does not match
-- every word -- "Ironbound" for Newark -- and null otherwise. Of several, the
-- one typed exactly, then one that starts with what was typed, then the
-- shortest: "kings" shows "Kings", not "Kings County".
create function public.search_places(
  p_query text,
  p_granularity text,
  p_area uuid[] default null
) returns table (id uuid, kind text, label text, in_area boolean, matched text)
language plpgsql
stable
set search_path = public
as $$
declare
  v_query text := lower(btrim(regexp_replace(coalesce(p_query, ''), '[\s,]+', ' ', 'g')));
  v_words text[];
  v_longest text;
  v_patterns text[];
  v_kinds text[];
begin
  v_kinds := case p_granularity
    when 'locality' then array['locality', 'borough']
    when 'neighborhood' then array['locality', 'borough', 'neighborhood']
    when 'area' then array['state', 'county', 'borough']
  end;
  if v_kinds is null then
    raise exception 'PLACE_GRANULARITY_INVALID';
  end if;

  if v_query ~ '^[0-9]{5}$' then
    if p_granularity = 'area' then
      return;
    end if;
    return query
    select p.id, p.kind, p.label, coalesce(p.area_ids && p_area, false), null::text
      from public.place_zips z
      join public.places p on p.id = z.place_id
     where z.zip = v_query
       and p.kind = any (v_kinds)
     order by
       coalesce(p.area_ids && p_area, false) desc,
       (p.kind = 'neighborhood') desc,
       z.share desc,
       p.label
     limit 10;
    return;
  end if;

  if char_length(v_query) < 2 or char_length(v_query) > 100 then
    return;
  end if;
  v_words := string_to_array(v_query, ' ');
  -- The LIKE on the longest word is what the trigram index serves; a type
  -- word may be spelled either way, so it is not the one.
  select w into v_longest
    from unnest(v_words) w
   order by (w in ('township', 'twp', 'borough', 'boro')), char_length(w) desc
   limit 1;
  if v_longest in ('township', 'twp', 'borough', 'boro') then
    v_longest := '';
  end if;
  -- Each word at a word start, with regex metacharacters escaped.
  select array_agg('(^|[^[:alnum:]])' || case
           when w in ('township', 'twp') then '(township|twp)'
           when w in ('borough', 'boro') then '(borough|boro)'
           else regexp_replace(w, '([^[:alnum:][:space:]])', '\\\1', 'g')
         end)
    into v_patterns
    from unnest(v_words) w;
  v_longest := replace(replace(replace(v_longest, '\', '\\'), '%', '\%'), '_', '\_');

  return query
  select p.id, p.kind, p.label, coalesce(p.area_ids && p_area, false),
         case when exists (
                select 1 from unnest(v_patterns) w where lower(p.label) !~ w
              )
           then (select a from unnest(p.aliases) a
                  where not exists (
                    select 1 from unnest(v_patterns) w where lower(a) !~ w
                  )
                  order by lower(a) = v_query desc,
                           lower(a) like v_query || '%' desc,
                           char_length(a)
                  limit 1)
         end
    from public.places p
   where p.kind = any (v_kinds)
     and p.search_text like '%' || v_longest || '%'
     and not exists (
       select 1 from unnest(v_patterns) w where p.search_text !~ w
     )
   order by
     coalesce(p.area_ids && p_area, false) desc,
     (lower(p.name) = v_query or v_query = any (select lower(a) from unnest(p.aliases) a)) desc,
     (lower(p.name) like v_query || '%'
       or exists (select 1 from unnest(p.aliases) a where lower(a) like v_query || '%')) desc,
     p.population desc nulls last,
     case
       when p.kind in ('state', 'borough') then 0
       when p.kind = 'locality' and p.place_type = 'CDP' then 2
       else 1
     end,
     char_length(p.label),
     p.label
   limit 10;
end;
$$;

comment on function public.search_places(text, text, uuid[]) is
  'Place autocomplete (#1699, #1700): at most 10 places of the kinds p_granularity allows (locality, neighborhood or area), places within p_area first -- those a five-digit ZIP covers, or those matching every word typed, with the alias that matched where the label does not. Raises PLACE_GRANULARITY_INVALID. Reads only the public places tables, so it runs as the caller.';

revoke execute on function public.search_places(text, text, uuid[]) from public;
grant execute on function public.search_places(text, text, uuid[]) to anon, authenticated;
