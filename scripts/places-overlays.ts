// Builds the places overlay migration (#1700): the ZIP shortcut's rows and
// the hand-curated aliases, on top of the places seed (#1699).
//
//   bun run places:overlays   # writes supabase/migrations/<VERSION>_places_overlays.sql
//
// Sources (public domain; vintages recorded in docs/spec/events.md,
// "Registration questions"):
//
//   - Census 2020 ZCTA relationship files: ZCTA to place, county subdivision,
//     county (the NYC boroughs) and tract
//   - NYC Planning 2020 census tract to NTA equivalency, via NYC Open Data,
//     which takes an NYC ZIP to its neighborhoods through its tracts
//   - scripts/places/aliases.ts, by hand
//
// Like the seed, nothing is fetched at runtime and nothing but the migration
// is written. Every key is checked against the seed migration, so a place the
// seed does not have is never named, and every alias's label against the one
// its author meant.

import { writeFileSync } from "node:fs";
import { PLACE_ALIASES } from "./places/aliases";
import { NYC_BOROUGHS } from "./places/build";
import { readSeedPlaces } from "./places/seed-file";
import { parseZctaRelationship, zipRows, type ZipRow } from "./places/zips";

const VERSION = "20261024120100";
const OUT = `supabase/migrations/${VERSION}_places_overlays.sql`;

const REL =
  "https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520";
const TRACT_NTA =
  "https://data.cityofnewyork.us/resource/hm78-6dwm.json?$select=geoid,ntacode&$limit=5000";

async function text(url: string): Promise<string> {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

const isNycCounty = (geoid: string) => geoid.slice(0, 5) in NYC_BOROUGHS;

const seed = readSeedPlaces();
const known = new Set(seed.keys());

for (const [key, { place }] of Object.entries(PLACE_ALIASES)) {
  const row = seed.get(key);
  if (row?.label !== place) {
    throw new Error(
      `aliases.ts: ${key} is "${row?.label ?? "missing"}", expected "${place}"`,
    );
  }
}

const [placeRel, cousubRel, countyRel, tractRel, tractNtaJson] =
  await Promise.all([
    text(`${REL}_place20_natl.txt`),
    text(`${REL}_cousub20_natl.txt`),
    text(`${REL}_county20_natl.txt`),
    text(`${REL}_tract20_natl.txt`),
    text(TRACT_NTA),
  ]);

const ntaByTract = new Map(
  (JSON.parse(tractNtaJson) as { geoid: string; ntacode: string }[]).map(
    ({ geoid, ntacode }) => [geoid, `nta:${ntacode}`],
  ),
);

const rows: ZipRow[] = [
  ...zipRows(
    parseZctaRelationship(placeRel, "PLACE_20"),
    (geoid) => `place:${geoid}`,
    known,
  ),
  ...zipRows(
    parseZctaRelationship(cousubRel, "COUSUB_20"),
    (geoid) => `cousub:${geoid}`,
    known,
  ),
  // NYC's ZIPs reach places through its boroughs and, at neighborhood
  // granularity, through the tracts each NTA is built from.
  ...zipRows(
    parseZctaRelationship(countyRel, "COUNTY_20", isNycCounty),
    (geoid) => `county:${geoid}`,
    known,
  ),
  ...zipRows(
    parseZctaRelationship(tractRel, "TRACT_20", isNycCounty),
    (geoid) => ntaByTract.get(geoid) ?? null,
    known,
  ),
];

function sqlText(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function migration(): string {
  const chunks: string[] = [];
  for (let i = 0; i < rows.length; i += 2000) {
    chunks.push(
      `insert into zip_seed values\n${rows
        .slice(i, i + 2000)
        .map((row) => `('${row.zip}','${row.key}',${row.share})`)
        .join(",\n")};`,
    );
  }
  const aliases = Object.entries(PLACE_ALIASES)
    .map(
      ([key, { aliases }]) =>
        `  (${sqlText(key)}, array[${aliases.map(sqlText).join(", ")}])`,
    )
    .join(",\n");
  const zips = new Set(rows.map((row) => row.zip)).size;

  return `-- GENERATED by \`bun run places:overlays\` (scripts/places-overlays.ts) -- do not edit.
-- The places overlays (#1700): ${rows.length} ZIP-to-place rows covering ${zips} ZIPs,
-- from the Census 2020 ZCTA relationship files and NYC Planning's 2020 tract to
-- NTA equivalency, and the aliases in scripts/places/aliases.ts. Sources and
-- vintages: docs/spec/events.md.

create temporary table zip_seed (
  zip text not null,
  key text not null,
  share real not null
);

${chunks.join("\n\n")}

insert into public.place_zips (zip, place_id, share)
select s.zip, public.place_key_id(s.key), s.share
  from zip_seed s
  join public.places p on p.id = public.place_key_id(s.key)
on conflict (zip, place_id) do update set share = excluded.share;

drop table zip_seed;

-- Aliases are added to what the seed gave, never replacing it.
update public.places p
   set aliases = array(
         select distinct a from unnest(p.aliases || extra.aliases) a order by a
       )
  from (values
${aliases}
  ) as extra (key, aliases)
 where p.id = public.place_key_id(extra.key);
`;
}

writeFileSync(OUT, migration());
const byPrefix = Object.groupBy(rows, (row) => row.key.split(":")[0]);
console.log(
  `${OUT}: ${rows.length} ZIP rows (${Object.entries(byPrefix)
    .map(([prefix, list]) => `${list?.length} ${prefix}`)
    .join(", ")}), aliases for ${Object.keys(PLACE_ALIASES).length} places`,
);
