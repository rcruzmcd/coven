// Adds one city's neighborhoods to the places table (#1700), from Who's On
// First, as a new migration.
//
//   bun run places:neighborhoods <place key> <WOF locality id> [--out <file>]
//   bun run places:neighborhoods place:4260000 101718083   # Philadelphia
//
// On demand, for a city a tenant's service area includes -- never the whole
// US. Find the city's key in the seed migration (`place:<GEOID>`) and its WOF
// id on https://spelunker.whosonfirst.org; the run fails when the two names
// differ. Only current neighbourhood and macrohood records whose source is
// CC0 or public domain are loaded (scripts/places/wof.ts); the run lists what
// it left out and why.
//
// Each neighborhood hangs off the city: kind `neighborhood`, labelled
// "<name>, <city's label>", ranked by the city's population shared among
// them, as NYC's NTAs are by their borough's. Ids are uuid v5 of
// `wof:<id>`, so running it again for the same city updates the same rows.
// Nothing is fetched at runtime; the output is a migration.

import { writeFileSync } from "node:fs";
import { readSeedPlaces } from "./places/seed-file";
import { WOF_PLACETYPES, wofPath, wofRows, type WofRecord } from "./places/wof";

const SPELUNKER = "https://spelunker.whosonfirst.org";
const DATA = "https://data.whosonfirst.org";
const MAX_PAGES = 200;
const CONCURRENCY = 2;
const RETRIES = 6;

const args = process.argv.slice(2);
const outIndex = args.indexOf("--out");
const out = outIndex >= 0 ? args.splice(outIndex, 2)[1] : null;
const [placeKey, wofIdArg] = args;
const wofId = Number(wofIdArg);
if (!placeKey || !Number.isInteger(wofId) || wofId <= 0) {
  console.error(
    "Usage: bun run places:neighborhoods <place key> <WOF locality id> [--out <file>]",
  );
  process.exit(1);
}

const city = readSeedPlaces().get(placeKey);
if (city?.kind !== "locality") {
  throw new Error(`${placeKey} is not a city or town in the places seed`);
}

// Both WOF hosts rate-limit; a 429 or 503 waits as asked, or backs off.
async function get(url: string): Promise<Response> {
  for (let attempt = 0; ; attempt++) {
    const response = await fetch(url);
    if (response.ok) return response;
    if (![429, 503].includes(response.status) || attempt === RETRIES) {
      throw new Error(`${url}: HTTP ${response.status}`);
    }
    const wait = Number(response.headers.get("retry-after")) || 2 ** attempt;
    await Bun.sleep(wait * 1000);
  }
}

async function record(id: number): Promise<WofRecord> {
  const json = (await (await get(`${DATA}/${wofPath(id)}`)).json()) as {
    properties: WofRecord;
  };
  return json.properties;
}

// The Spelunker's descendants page is HTML only, ten to a page; the record
// links carry the ids.
async function descendantIds(placetype: string): Promise<number[]> {
  const ids = new Set<number>();
  for (let page = 1; page <= MAX_PAGES; page++) {
    const html = await (
      await get(
        `${SPELUNKER}/id/${wofId}/descendants/?placetype=${placetype}&page=${page}`,
      )
    ).text();
    const found = [
      ...html.matchAll(/href="\/id\/(\d+)" class="wof-place-name/g),
    ].map((match) => Number(match[1]));
    if (found.length === 0) break;
    found.forEach((id) => ids.add(id));
  }
  return [...ids];
}

async function mapLimit<T, R>(items: T[], fn: (item: T) => Promise<R>) {
  const results: R[] = [];
  for (let i = 0; i < items.length; i += CONCURRENCY) {
    results.push(
      ...(await Promise.all(items.slice(i, i + CONCURRENCY).map(fn))),
    );
  }
  return results;
}

const locality = await record(wofId);
const normalize = (name: string) =>
  name.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
if (
  locality["wof:placetype"] !== "locality" ||
  normalize(locality["wof:name"] ?? "") !== normalize(city.name)
) {
  throw new Error(
    `WOF ${wofId} is the ${locality["wof:placetype"]} "${locality["wof:name"]}", not ${city.label}`,
  );
}

const ids = (
  await Promise.all(WOF_PLACETYPES.map((placetype) => descendantIds(placetype)))
).flat();
const { rows, skipped } = wofRows(await mapLimit(ids, record));
if (rows.length === 0) {
  console.error(
    `No loadable neighborhoods for ${city.label}: ${skipped.length} records left out.`,
  );
  for (const skip of skipped) {
    console.error(`  ${skip.id} ${skip.name || "(no name)"}: ${skip.reason}`);
  }
  process.exit(1);
}

const sqlText = (value: string) => `'${value.replaceAll("'", "''")}'`;
const version = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
const slug = normalize(city.name)
  .replace(/[^a-z0-9]+/g, "_")
  .replace(/^_|_$/g, "");
const path =
  out ?? `supabase/migrations/${version}_places_neighborhoods_${slug}.sql`;

writeFileSync(
  path,
  `-- GENERATED by \`bun run places:neighborhoods ${placeKey} ${wofId}\`
-- (scripts/places-neighborhoods.ts) -- do not edit.
-- ${city.label}: ${rows.length} neighborhoods from Who's On First (CC0 records
-- only, ${skipped.length} left out). See docs/spec/events.md, "Place questions".

do $$
begin
  if not exists (select 1 from public.places
                  where id = public.place_key_id(${sqlText(placeKey)})
                    and kind = 'locality') then
    raise exception 'places: ${placeKey} is missing';
  end if;
end $$;

create temporary table wof_seed (key text primary key, name text not null);

insert into wof_seed values
${rows.map((row) => `(${sqlText(row.key)},${sqlText(row.name)})`).join(",\n")};

insert into public.places
  (id, kind, name, label, parent_id, area_ids, state_code, county_name,
   source, source_id, population)
select public.place_key_id(s.key), 'neighborhood', s.name,
       s.name || ', ' || city.label, city.id,
       public.place_key_id(s.key) || city.area_ids, city.state_code,
       city.county_name, 'whosonfirst', split_part(s.key, ':', 2),
       round(city.population::numeric / (select count(*) from wof_seed))::integer
  from wof_seed s
  join public.places city on city.id = public.place_key_id(${sqlText(placeKey)})
on conflict (source, source_id) do update
   set name = excluded.name, label = excluded.label,
       parent_id = excluded.parent_id, area_ids = excluded.area_ids,
       population = excluded.population;

drop table wof_seed;
`,
);
console.log(
  `${path}: ${rows.length} neighborhoods of ${city.label}, ${skipped.length} records left out`,
);
const reasons = Object.groupBy(skipped, (skip) => skip.reason);
for (const [reason, list] of Object.entries(reasons)) {
  console.log(`  ${list?.length} ${reason}`);
}
